def ce(emoji_id: str | int, fallback: str) -> str:
    return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'


def e(name: str) -> str:
    emoji_id, fallback = _IDS[name]
    return ce(emoji_id, fallback)


def fb(name: str) -> str:
    return _IDS[name][1]